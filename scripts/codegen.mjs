import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const addonPath = path.join(rootDir, 'build', 'norch_native.node');
const outDir = path.join(rootDir, 'src', 'generated');
const outFile = path.join(outDir, 'aten_ops.ts');

const native = require(addonPath);
const schemas = native.getAllSchemas('aten::');

const RESERVED = new Set([
  'default',
  'in',
  'class',
  'var',
  'function',
  'return',
  'new',
  'delete',
  'switch',
  'export',
  'import',
  'typeof',
  'void',
  'this',
  'super',
]);

function mapSchemaType(typeStr, realTypeStr) {
  const real = realTypeStr || typeStr;
  if (typeStr.endsWith('?')) {
    const inner = mapSchemaType(typeStr.slice(0, -1), real.endsWith('?') ? real.slice(0, -1) : real);
    return `${inner} | null | undefined`;
  }
  if (real === 'ScalarType') return 'DType | number';
  if (real === 'Layout') return 'string | number';
  if (real === 'MemoryFormat') return 'string | number';
  if (typeStr === 'Tensor') return 'Tensor';
  if (typeStr === 'Generator') return 'Generator';
  if (typeStr === 'int' || typeStr === 'SymInt') return 'number | bigint';
  if (typeStr === 'float' || typeStr === 'SymFloat') return 'number';
  if (typeStr === 'bool' || typeStr === 'SymBool') return 'boolean';
  if (typeStr === 'Scalar') return 'number | boolean | bigint';
  if (typeStr === 'str') return 'string';
  if (typeStr === 'Device') return 'DeviceLike';
  if (typeStr === 'Tensor[]') return 'Tensor[]';
  if (typeStr === 'Tensor?[]') return '(Tensor | null | undefined)[]';
  if (typeStr === 'int[]' || typeStr === 'SymInt[]' || /^int\[\d+\]$/.test(typeStr)) {
    return 'number[] | number';
  }
  if (typeStr === 'float[]' || /^float\[\d+\]$/.test(typeStr)) return 'number[] | number';
  if (typeStr === 'bool[]' || /^bool\[\d+\]$/.test(typeStr)) return 'boolean[]';
  if (typeStr === 'str[]') return 'string[]';
  return 'unknown';
}

function mapReturnType(rets) {
  if (!rets || rets.length === 0) return 'void';
  if (rets.length === 1) {
    const t = rets[0].type;
    if (t === 'Tensor') return 'Tensor';
    if (t === 'Tensor[]') return 'Tensor[]';
    if (t === 'int' || t === 'SymInt' || t === 'float' || t === 'Scalar') return 'number';
    if (t === 'bool') return 'boolean';
    if (t === 'str') return 'string';
    return 'unknown';
  }
  const parts = rets.map((r) => {
    if (r.type === 'Tensor') return 'Tensor';
    if (r.type === 'Tensor[]') return 'Tensor[]';
    if (r.type === 'int' || r.type === 'float' || r.type === 'Scalar') return 'number';
    if (r.type === 'bool') return 'boolean';
    return 'unknown';
  });
  return `[${parts.join(', ')}]`;
}

function formatOverloadSignature(opName, schema) {
  const posArgs = schema.arguments.filter((a) => !a.kwargOnly);
  const kwArgs = schema.arguments.filter((a) => a.kwargOnly);
  const params = [];
  let sawOptional = false;
  for (const a of posArgs) {
    const safeName = RESERVED.has(a.name) ? `${a.name}_` : a.name;
    const isOpt = sawOptional || a.hasDefault || a.type.endsWith('?');
    if (isOpt) sawOptional = true;
    params.push(`${safeName}${isOpt ? '?' : ''}: ${mapSchemaType(a.type, a.realType)}`);
  }
  if (kwArgs.length > 0) {
    const fields = kwArgs
      .map((a) => `${a.name}?: ${mapSchemaType(a.type, a.realType)}`)
      .join('; ');
    params.push(`options?: { ${fields} }`);
  }
  const ret = mapReturnType(schema.returns);
  return `${opName}(${params.join(', ')}): ${ret};`;
}

// Group public ATen ops (skip internal `_`-prefixed ops, `out` variants, backward internals)
const grouped = new Map();
for (const s of schemas) {
  const shortName = s.name.replace(/^aten::/, '');
  if (shortName.startsWith('_')) continue;
  if (shortName.endsWith('_backward')) continue;
  if (s.overload.includes('out')) continue;
  if (!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(shortName)) continue;

  let list = grouped.get(shortName);
  if (!list) {
    list = [];
    grouped.set(shortName, list);
  }
  list.push(s);
}

const sortedNames = [...grouped.keys()].sort();

const lines = [
  '// AUTO-GENERATED by scripts/codegen.mjs from live libtorch c10::Dispatcher schemas.',
  `// Total ATen schemas discovered: ${schemas.length}, public ops exposed: ${sortedNames.length}`,
  '// Do not edit by hand.',
  '',
  "import type { DType } from '../dtype.js';",
  "import type { DeviceLike } from '../device.js';",
  "import type { Generator } from '../generator.js';",
  "import { Tensor, wrapResult } from '../tensor.js';",
  "import { native } from '../native.js';",
  '',
  'export interface AtenOps {',
];

let totalOverloads = 0;

for (const opName of sortedNames) {
  const overloads = grouped.get(opName);
  // Emit deduplicated overload signatures for every non-out overload, plus a fallback for kwargs-style calls
  const seenSigs = new Set();
  const emitted = [];
  for (const ov of overloads) {
    const sig = formatOverloadSignature(opName, ov);
    if (!seenSigs.has(sig)) {
      seenSigs.add(sig);
      emitted.push(sig);
    }
  }
  for (const sig of emitted) {
    lines.push(`  ${sig}`);
    totalOverloads += 1;
  }
  if (overloads.length > 1) {
    const primary = overloads.find((o) => o.overload === '') ?? overloads[0];
    lines.push(`  ${opName}(...args: unknown[]): ${mapReturnType(primary.returns)};`);
  }
}

lines.push('}');
lines.push('');
lines.push('export const ATEN_OP_NAMES: readonly string[] = [');
for (const opName of sortedNames) {
  lines.push(`  ${JSON.stringify(opName)},`);
}
lines.push('];');
lines.push('');
lines.push('function isPlainOptionsObject(v: unknown): v is Record<string, unknown> {');
lines.push("  if (v === null || typeof v !== 'object') return false;");
lines.push('  if (Array.isArray(v) || ArrayBuffer.isView(v)) return false;');
lines.push('  if (v instanceof Tensor) return false;');
lines.push("  if ('_native' in v) return false;");
lines.push('  const proto = Object.getPrototypeOf(v);');
lines.push('  return proto === Object.prototype || proto === null;');
lines.push('}');
lines.push('');
lines.push('function createAtenOpCaller(opName: string): (...args: unknown[]) => unknown {');
lines.push('  return (...args: unknown[]) => {');
lines.push('    let kwArgs: Record<string, unknown> | undefined;');
lines.push('    let posArgs = args;');
lines.push('    if (args.length > 0 && isPlainOptionsObject(args[args.length - 1])) {');
lines.push('      kwArgs = args[args.length - 1] as Record<string, unknown>;');
lines.push('      posArgs = args.slice(0, -1);');
lines.push('    }');
lines.push('    const raw = native.callOpAuto(opName, posArgs, kwArgs);');
lines.push('    return wrapResult(raw);');
lines.push('  };');
lines.push('}');
lines.push('');
lines.push('const cache = new Map<string, (...args: unknown[]) => unknown>();');
lines.push('');
lines.push('export const aten: AtenOps & Record<string, (...args: unknown[]) => unknown> = new Proxy(');
lines.push('  {} as AtenOps & Record<string, (...args: unknown[]) => unknown>,');
lines.push('  {');
lines.push('    get(_target, prop) {');
lines.push("      if (typeof prop !== 'string') return undefined;");
lines.push('      let fn = cache.get(prop);');
lines.push('      if (!fn) {');
lines.push('        fn = createAtenOpCaller(prop);');
lines.push('        cache.set(prop, fn);');
lines.push('      }');
lines.push('      return fn;');
lines.push('    },');
lines.push('  }');
lines.push(');');
lines.push('');

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(
  `[norch codegen] generated ${outFile} (${sortedNames.length} public ops, ${totalOverloads} typed overloads from ${schemas.length} ATen schemas)`
);
